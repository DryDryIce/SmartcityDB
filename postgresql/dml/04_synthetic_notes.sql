-- Para completar el modelo relacional y permitir consultas como "sensores instalados por año", se asignaron años sintéticos controlados.

-- Estos valores NO corresponden a años reales confirmados por EPA.

-- Los datos originales se mantienen sin modificar dentro de data/raw/.

-- Años sintéticos asignados:

-- EPA-BRONX-0110      -> 2018
-- EPA-BRONX-0112      -> 2020
-- EPA-BROOKLYN-0052   -> 2017
-- EPA-BROOKLYN-0118   -> 2021
-- EPA-QUEENS-0124     -> 2019
-- EPA-QUEENS-0125     -> 2022

-- El objetivo es únicamente completar valores faltantes para fines académicos, de modelado y de consulta.